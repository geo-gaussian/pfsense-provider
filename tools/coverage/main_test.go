func TestCoverageBadgeBoundaries(t *testing.T) {
	tests := []struct {
		covered int64
		total   int64
		color   string
		message string
	}{
		{0, 0, "lightgrey", "unavailable"},
		{4999, 10000, "red", "49.99%"},
		{5000, 10000, "orange", "50.00%"},
		{6999, 10000, "orange", "69.99%"},
		{7000, 10000, "yellow", "70.00%"},
		{7999, 10000, "yellow", "79.99%"},
		{8000, 10000, "yellowgreen", "80.00%"},
		{9499, 10000, "yellowgreen", "94.99%"},
		{949999, 1000000, "yellowgreen", "94.99%"},
		{9500, 10000, "brightgreen", "95.00%"},
		{9223372036854775807, 9223372036854775807, "brightgreen", "100.00%"},
	}
	for _, tt := range tests {
		b, err := coverageBadge("test", tt.covered, tt.total)
		if err != nil || b.Color != tt.color || b.Message != tt.message {
			t.Errorf("%d/%d: got %+v, %v", tt.covered, tt.total, b, err)
		}
	}
	if _, err := coverageBadge("test", 2, 1); err == nil {
		t.Fatal("accepted invalid coverage")
	}
}

func TestInventoryIncludesOnlyDocumentedOperations(t *testing.T) {
	spec := []byte("paths:\n  /a:\n    parameters: []\n    get:\n      operationId: A\n    post: {}\n  /b:\n    delete:\n      operationId: B\n")
	mappings := map[string]evidence{"A": {Method: "GET", Path: "/a"}}
	ops, err := inventory(spec, mappings)
	if err != nil || len(ops) != 3 || !ops[0].Supported || ops[1].Supported {
		t.Fatalf("unexpected inventory: %+v, %v", ops, err)
	}
	mappings["A"] = evidence{Method: "PUT", Path: "/a"}
	if _, err := inventory(spec, mappings); err == nil {
		t.Fatal("accepted wrong method")
	}
	mappings["A"] = evidence{Method: "GET", Path: "/missing"}
	if _, err := inventory(spec, mappings); err == nil {
		t.Fatal("accepted wrong path")
	}
	if _, err := inventory([]byte("paths:\n  /a:\n    $ref: '#/other'\n"), nil); err == nil {
		t.Fatal("accepted unresolved path reference")
	}
	if _, err := inventory([]byte("paths:\n  /a:\n    get: {operationId: A}\n    post: {operationId: A}\n"), nil); err == nil {
		t.Fatal("accepted duplicate operation ID")
	}
}

func TestFilterProfile(t *testing.T) {
	t.Chdir(t.TempDir())
	for name, content := range map[string]string{
		"custom.go":    "package example\n",
		"generated.go": "// Code generated by test DO NOT EDIT.\npackage example\n",
	} {
		if err := os.WriteFile(filepath.FromSlash(name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	profile := "mode: atomic\n" +
		module + "custom.go:1.1,2.1 3 1\n" +
		module + "custom.go:2.1,3.1 2 0\n" +
		module + "generated.go:1.1,2.1 20 1\n" +
		module + "tools/coverage/main.go:1.1,2.1 30 1\n"
	result, covered, total, err := filterProfile([]byte(profile))
	if err != nil || covered != 3 || total != 5 || strings.Contains(string(result), "generated.go") || strings.Contains(string(result), "tools/coverage") {
		t.Fatalf("unexpected filtered profile: %q, %d/%d, %v", result, covered, total, err)
	}
	if _, _, _, err := filterProfile([]byte("mode: atomic\n" + module + "custom.go:1.1,2.1 invalid 1\n")); err == nil {
		t.Fatal("accepted malformed profile")
	}
}
